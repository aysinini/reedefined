// ── LANGUAGE ENGINE ──
function getLang() {
  return localStorage.getItem('rd-lang') || 'en';
}

function setLang(lang) {
  localStorage.setItem('rd-lang', lang);
  applyLang(lang);
  updateSwitcher(lang);
}

function t(key) {
  const lang = getLang();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key] || key;
}

function applyLang(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key];
    if (val) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key];
    if (val) el.placeholder = val;
  });
}

function updateSwitcher(lang) {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const isOn = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('on', isOn);
    btn.style.opacity = isOn ? '1' : '.55';
    btn.style.fontWeight = isOn ? '700' : '600';
  });
}

// Auto-apply on load
document.addEventListener('DOMContentLoaded', () => {
  const lang = getLang();
  applyLang(lang);
  updateSwitcher(lang);
});

